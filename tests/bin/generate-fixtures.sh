#!/usr/bin/env bash
# Generates test fixtures from REAL Composer output on the synthetic, public
# lock files in tests/fixtures/locks/<scenario>/.
#
# Run inside a container with Composer and network access, e.g. from a
# project that has this module installed:
#   ddev exec bash vendor/webium/silverstripe-composer-report/tests/bin/generate-fixtures.sh [--refresh-locks]
#
# Output per scenario in tests/fixtures/composer/:
#   <scenario>.<command>.json        stdout
#   <scenario>.<command>.stderr.txt  stderr
#   <scenario>.<command>.exitcode    exit code
# plus GENERATED.txt with the Composer and PHP versions and the date.

set -euo pipefail

cd "$(dirname "$0")/.."
locks=fixtures/locks
out=fixtures/composer

refresh=0
if [ "${1:-}" = "--refresh-locks" ]; then
    refresh=1
fi

# No git version guessing for the synthetic root packages, no plugins or scripts
export COMPOSER_ROOT_VERSION=dev-main
export COMPOSER_NO_INTERACTION=1

mkdir -p "$out"

run() {
    local dir=$1 name=$2 label=$3
    shift 3
    local code=0
    composer "$@" --working-dir="$dir" --locked --format=json --no-plugins --no-scripts --no-ansi \
        > "$out/$name.$label.json" 2> "$out/$name.$label.stderr.txt" || code=$?
    echo "$code" > "$out/$name.$label.exitcode"
}

for dir in "$locks"/*/; do
    dir=${dir%/}
    name=$(basename "$dir")

    if [ "$refresh" = 1 ] || [ ! -f "$dir/composer.lock" ]; then
        composer update --working-dir="$dir" --no-install --no-plugins --no-scripts \
            --ignore-platform-reqs --no-progress --quiet
    fi

    run "$dir" "$name" audit audit
    run "$dir" "$name" outdated outdated
    run "$dir" "$name" outdated-direct outdated --direct
done

{
    echo "Generated by tests/bin/generate-fixtures.sh"
    echo "Date (UTC): $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "Composer:   $(composer --version --no-ansi 2>/dev/null | head -1)"
    echo "PHP:        $(php -r 'echo PHP_VERSION;')"
} > "$out/GENERATED.txt"

# Summary, so that the counts asserted in the tests can be updated after regenerating
php -r '
foreach (glob($argv[1] . "/*.audit.json") as $file) {
    $data = json_decode((string) file_get_contents($file), true);
    $advisories = is_array($data["advisories"] ?? null) ? array_sum(array_map("count", $data["advisories"])) : 0;
    $abandoned = is_array($data["abandoned"] ?? null) ? count($data["abandoned"]) : 0;
    printf("%-40s advisories=%d abandoned=%d\n", basename($file), $advisories, $abandoned);
}
foreach (glob($argv[1] . "/*.outdated*.json") as $file) {
    $data = json_decode((string) file_get_contents($file), true);
    $rows = is_array($data) ? (is_array($data["locked"] ?? null) ? $data["locked"] : ($data["installed"] ?? [])) : [];
    printf("%-40s packages=%d\n", basename($file), count($rows));
}
' "$out"
